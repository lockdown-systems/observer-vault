#!/usr/bin/env bash
#
# Observer Vault: Merge Upstream Signal-Desktop
#
# This script helps automate merging new Signal-Desktop releases into Observer Vault.
# It handles common conflict patterns automatically and highlights files needing manual review.
#
# Usage:
#   ./scripts/merge-upstream.sh v7.88.0
#
# Prerequisites:
#   - You must have 'upstream' remote pointing to Signal-Desktop
#   - Working directory must be clean (no uncommitted changes)
#
set -euo pipefail

# Colors for output
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m' # No Color

# Files that should ALWAYS accept upstream version (no Observer Vault customizations)
AUTO_ACCEPT_UPSTREAM=(
    # Locale files - Observer Vault is not localized
    "_locales/*/messages.json"
    
    # Generated files - will be regenerated
    "ACKNOWLEDGMENTS.md"
    
    # Documentation we don't customize
    "CONTRIBUTING.md"
    "SECURITY.md"
    
    # Storybook (we don't customize)
    ".storybook/**"
    "sticker-creator/**"
)

# Files/directories from upstream that should be DELETED (not used in Observer Vault)
DELETE_FROM_UPSTREAM=(
    # Issue templates - we don't want Signal's issue templates
    ".github/ISSUE_TEMPLATE"
    
    # PR template - we have our own workflow
    ".github/PULL_REQUEST_TEMPLATE.md"
    
    # Dependabot - we manage dependencies manually
    ".github/dependabot.yml"
)

# Workflow files that should be DISABLED (renamed to .disabled)
# These are upstream workflows we don't run but keep for reference
